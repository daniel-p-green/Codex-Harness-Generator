#!/usr/bin/env python3
"""Record an eval-gate snapshot for trend tracking.

The release gate answers "did this pass now?" This script preserves a compact
history so regressions, newly added checks, and duration/step changes are visible
over time without relying on CI logs.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_HISTORY_DIR = REPO_ROOT / "Docs" / "Environment" / "eval-history"
DEFAULT_REPORT = REPO_ROOT / "Docs" / "Environment" / "EVAL_TRENDS.md"


def run_eval_gate(extra_args: list[str]) -> dict:
    completed = subprocess.run(
        [sys.executable, "scripts/run_evals.py", "--json", *extra_args],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    try:
        payload = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"run_evals.py did not emit valid JSON: {exc}\n{completed.stdout}\n{completed.stderr}")
    payload["returncode"] = completed.returncode
    return payload


def summarize(payload: dict, generated: str, label: str) -> dict:
    steps = payload.get("steps", [])
    return {
        "generated": generated,
        "label": label,
        "status": payload.get("status", "unknown"),
        "returncode": payload.get("returncode"),
        "step_count": len(steps),
        "passed": sum(1 for step in steps if step.get("status") == "pass"),
        "failed": sum(1 for step in steps if step.get("status") == "fail"),
        "steps": [
            {
                "name": step.get("name"),
                "status": step.get("status"),
                "returncode": step.get("returncode"),
            }
            for step in steps
        ],
    }


def snapshot_name(generated: str, label: str) -> str:
    safe_label = "".join(char if char.isalnum() or char in "-_" else "-" for char in label.lower()).strip("-")
    suffix = f"-{safe_label}" if safe_label else ""
    return generated.replace(":", "").replace("-", "") + suffix + ".json"


def write_snapshot(history_dir: Path, summary: dict) -> Path:
    history_dir.mkdir(parents=True, exist_ok=True)
    path = history_dir / snapshot_name(summary["generated"], summary["label"])
    path.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return path


def load_snapshots(history_dir: Path) -> list[dict]:
    if not history_dir.exists():
        return []
    snapshots = []
    for path in sorted(history_dir.glob("*.json")):
        snapshots.append(json.loads(path.read_text(encoding="utf-8")))
    return snapshots


def write_report(report_path: Path, snapshots: list[dict]) -> None:
    lines = [
        "# Eval Trends",
        "",
        "This report is generated by `python scripts/record_eval_snapshot.py`.",
        "It tracks release-gate health over time so regressions are visible",
        "without searching CI logs.",
        "",
        "| Generated | Label | Status | Passed | Failed | Steps |",
        "|---|---|---|---:|---:|---:|",
    ]
    for snapshot in sorted(snapshots, key=lambda item: item["generated"], reverse=True):
        lines.append(
            "| {generated} | `{label}` | {status} | {passed} | {failed} | {step_count} |".format(
                generated=snapshot["generated"],
                label=snapshot["label"],
                status=snapshot["status"].upper(),
                passed=snapshot["passed"],
                failed=snapshot["failed"],
                step_count=snapshot["step_count"],
            )
        )
    lines.extend(
        [
            "",
            "## Scope",
            "",
            "- Captures the offline eval gate by default.",
            "- Use `--eval-arg --codex-live --eval-arg --codex-live-profile --eval-arg all`",
            "  for authenticated live-smoke trend snapshots.",
            "- Use task-trial reports separately for generated-harness usefulness checks.",
        ]
    )
    report_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--label", default="offline", help="Short label for the snapshot")
    parser.add_argument("--history-dir", default=DEFAULT_HISTORY_DIR.as_posix())
    parser.add_argument("--report", default=DEFAULT_REPORT.as_posix())
    parser.add_argument("--generated", default=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"))
    parser.add_argument("--eval-arg", action="append", default=[], help="Extra argument passed to run_evals.py; repeatable")
    parser.add_argument("--input-json", help="Use an existing run_evals.py JSON payload instead of running the gate")
    parser.add_argument("--json", action="store_true", help="Emit the compact summary JSON")
    args = parser.parse_args()

    payload = json.loads(Path(args.input_json).read_text(encoding="utf-8")) if args.input_json else run_eval_gate(args.eval_arg)
    if "returncode" not in payload:
        payload["returncode"] = 0 if payload.get("status") == "pass" else 1
    summary = summarize(payload, args.generated, args.label)
    snapshot_path = write_snapshot(Path(args.history_dir), summary)
    snapshots = load_snapshots(Path(args.history_dir))
    write_report(Path(args.report), snapshots)

    output = {**summary, "snapshot": snapshot_path.as_posix(), "report": Path(args.report).as_posix()}
    if args.json:
        print(json.dumps(output, indent=2))
    else:
        print(f"Eval snapshot: {summary['status'].upper()}")
        print(f"- snapshot: {snapshot_path}")
        print(f"- report: {args.report}")
        print(f"- steps: {summary['passed']} passed, {summary['failed']} failed")
    return 0 if summary["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
